/**
 * Делит оставшиеся минуты между ненаписанными уроками так, чтобы сумма
 * точно совпала с длительностью курса. Простое деление с округлением
 * этого не даёт, и карточка начинает врать на несколько минут.
 */
function splitRemaining(total: number, parts: number): number[] {
  if (parts <= 0) return []
  const base = Math.max(1, Math.floor(total / parts))
  const durations = Array(parts).fill(base)

  // Остаток раскидываем по одной минуте с начала, чтобы ничего не потерять
  let rest = total - base * parts
  for (let i = 0; rest > 0; i = (i + 1) % parts) {
    durations[i] += 1
    rest -= 1
  }
  return durations
}

function buildLessons(course: Course): Lesson[] {
  const authored = AUTHORED[course.id] ?? []
  const authoredMinutes = authored
    .slice(0, course.lessonsCount)
    .reduce((sum, lesson) => sum + lesson.durationMin, 0)

  const placeholderCount = Math.max(0, course.lessonsCount - authored.length)
  const placeholderMinutes = splitRemaining(
    Math.max(placeholderCount, course.durationMin - authoredMinutes),
    placeholderCount,
  )

  let placeholderIndex = 0

  return Array.from({ length: course.lessonsCount }, (_, i) => {
    const order = i + 1
    const src = authored[i]
    if (!src) return placeholderLesson(course, order, placeholderMinutes[placeholderIndex++])

    return {
      id: `${course.id}-l${order}`,
      courseId: course.id,
      order,
      title: src.title,
      durationMin: src.durationMin,
      blocks: src.blocks,
    }
  })
}

export const LESSONS_BY_COURSE: Record<string, Lesson[]> = Object.fromEntries(
  COURSES.map((course) => [course.id, buildLessons(course)]),
)

/*
 * Данные курса и его уроков живут в разных файлах и легко расходятся:
 * добавили урок — забыли поправить длительность в карточке. При разработке
 * такие расхождения должны быть шумными, в проде проверка вырезается сборкой.
 */
if (import.meta.env.DEV) {
  for (const course of COURSES) {
    const lessons = LESSONS_BY_COURSE[course.id] ?? []
    const total = lessons.reduce((sum, lesson) => sum + lesson.durationMin, 0)

    if (lessons.length !== course.lessonsCount) {
      console.warn(
        `[data] «${course.title}»: уроков ${lessons.length}, а в карточке ${course.lessonsCount}`,
      )
    }
    if (total !== course.durationMin) {
      console.warn(
        `[data] «${course.title}»: сумма уроков ${total} мин, а в карточке ${course.durationMin} мин`,
      )
    }
  }
}
