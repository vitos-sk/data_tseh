/** Пока урок не написан — показываем честную заглушку, а не пустой экран. */
function placeholderLesson(course: Course, order: number): Lesson {
  return {
    id: `${course.id}-l${order}`,
    courseId: course.id,
    order,
    title: `Урок ${order}`,
    durationMin: Math.max(3, Math.round(course.durationMin / course.lessonsCount)),
    blocks: [
      {
        type: 'callout',
        tone: 'info',
        text: 'Этот урок ещё готовится. Текст и иллюстрации появятся здесь в ближайшем обновлении.',
      },
      {
        type: 'text',
        text: `Курс «${course.title}» — ${course.description}`,
      },
      {
        type: 'image',
        cover: course.cover,
        caption: 'Место для иллюстрации урока',
      },
    ],
  }
}

function buildLessons(course: Course): Lesson[] {
  const authored = AUTHORED[course.id] ?? []

  return Array.from({ length: course.lessonsCount }, (_, i) => {
    const order = i + 1
    const src = authored[i]
    if (!src) return placeholderLesson(course, order)

    return {
      id: `${course.id}-l${order}`,
      courseId: course.id,
      order,
      title: src.title,
      durationMin: src.durationMin,
      blocks: src.blocks,
    }
  })
}

export const LESSONS_BY_COURSE: Record<string, Lesson[]> = Object.fromEntries(
  COURSES.map((course) => [course.id, buildLessons(course)]),
)
